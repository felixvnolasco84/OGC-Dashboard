import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build, preview } from "vite";
import react from "@vitejs/plugin-react";
import { chromium, expect } from "@playwright/test";

const root = fileURLToPath(new URL("../", import.meta.url));
const outDir = `${root}/output/indirectos-ui-build`;
await build({ configFile: false, root, plugins: [react()], resolve: { alias: { "@": `${root}/src`, "convex/react": `${root}/e2e/indirectos/convex-stub.ts` } }, build: { outDir, emptyOutDir: true, rollupOptions: { input: `${root}/e2e/indirectos/preview.html` } }, logLevel: "error" });
const server = await preview({ configFile: false, root, build: { outDir }, preview: { host: "127.0.0.1", port: 4197, strictPort: true } });
let browser;
try {
  browser = await chromium.launch({ channel: "chrome", headless: true });
  await mkdir(`${root}/output/indirectos-ui`, { recursive: true });
  for (const width of [390, 1440]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = []; page.on("pageerror", error => { errors.push(error.message); console.error(error.message); });
    await page.goto("http://127.0.0.1:4197/e2e/indirectos/preview.html?view=budget");
    await expect(page.getByText("Indirectos automáticos", { exact: true })).toBeVisible();
    const row = page.getByRole("row").filter({ hasText: "Indirectos automáticos" });
    if (width === 1440) await expect(page.getByRole("columnheader", { name: "Avance", exact: true })).toBeVisible();
    await expect(page.getByRole("row").filter({ hasText: "OBRA" }).first().getByRole("cell").nth(4)).toContainText("50.00%");
    await expect(row).not.toContainText("10%");
    await expect(row).toContainText("10,000");
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    const field = page.getByLabel("Indirectos (%)", { exact: true });
    const save = page.getByRole("button", { name: "Guardar Cambios", exact: true });
    await expect(field).toHaveValue("10");
    await expect(save).toBeDisabled();
    await field.fill("20");
    await expect(save).toBeDisabled();
    const review = page.getByRole("region", { name: "Impacto financiero" });
    await expect(review).toBeVisible();
    await expect(review).toContainText("$20,000.00");
    await expect(save).toBeEnabled();
    await page.getByRole("button", { name: "Ver impacto antes de guardar" }).click();
    assert.equal(await review.evaluate(element => element.parentElement === document.activeElement), true);
    const layout = await page.getByRole("dialog").evaluate(element => {
      const bounds = element.getBoundingClientRect(), scroll = element.querySelector("[data-project-form-scroll]");
      return { left: bounds.left, right: bounds.right, viewport: window.innerWidth, overflow: scroll.scrollWidth > scroll.clientWidth };
    });
    assert.ok(layout.left >= 0 && layout.right <= layout.viewport);
    assert.equal(layout.overflow, false);
    const scrollSection = async locator => locator.evaluate(element => {
      const scroll = element.closest("[data-project-form-scroll]");
      scroll.scrollTop += element.getBoundingClientRect().top - scroll.getBoundingClientRect().top;
    });
    await scrollSection(page.getByRole("heading", { name: "Impacto al guardar" }));
    await page.screenshot({ path: `${root}/output/indirectos-ui/impact-budget-${width}.png` });
    await scrollSection(page.getByRole("heading", { name: "P&L · MXN" }));
    await page.screenshot({ path: `${root}/output/indirectos-ui/impact-pnl-${width}.png` });
    await page.getByLabel("Periodo de revisión de P&L").click();
    await page.getByRole("option", { name: "2026-10", exact: true }).click();
    await expect(review).toContainText("El filtro mensual no limita el alcance del guardado.");
    // Data updates invalidate the reviewed scope without replacing the draft.
    await page.getByLabel("Nombre del Proyecto *", { exact: true }).fill("Borrador local");
    await page.evaluate(() => window.feeFixtureChange({ paymentBase: 110000, project: { descripcion: "Actualización externa" } }));
    await expect(page.getByLabel("Nombre del Proyecto *", { exact: true })).toHaveValue("Borrador local");
    await expect(save).toBeDisabled();
    await page.getByRole("button", { name: "Revisar actualización" }).click();
    await expect(save).toBeEnabled();
    await page.evaluate(() => window.feeFixtureChange({ project: { nombre: "Nombre externo" } }));
    await expect(save).toBeDisabled();
    await page.getByRole("button", { name: "Usar valores actuales en esos campos" }).click();
    await expect(page.getByLabel("Nombre del Proyecto *", { exact: true })).toHaveValue("Nombre externo");
    await page.evaluate(() => window.feeFixtureChange({ previewFailure: true }));
    const previewError = page.getByRole("alert").filter({ hasText: "No se pudo calcular el impacto completo. Error de prueba." });
    await expect(previewError).toBeVisible();
    assert.equal(await previewError.evaluate(element => element.closest("[data-project-form-scroll]") === null), true);
    const retry = page.getByRole("button", { name: "Reintentar cálculo", exact: true });
    await expect(retry).toBeInViewport();
    await retry.click();
    await expect(previewError).toBeVisible();
    await expect(save).toBeDisabled();
    await expect(field).toHaveValue("20");
    await page.evaluate(() => window.feeFixtureChange({ previewFailure: false }));
    await expect(save).toBeEnabled();
    await page.evaluate(() => window.feeFixtureChange({ mutationFailure: true }));
    await save.click();
    await expect(page.getByRole("dialog")).toBeVisible();
    await expect(field).toHaveValue("20");
    await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Error de guardado de prueba");
    await expect(save).toBeEnabled();
    await page.evaluate(() => window.feeFixtureChange({ mutationFailure: false, delayedMutation: true }));
    await save.click();
    await expect(page.getByRole("button", { name: "Guardando...", exact: true })).toBeDisabled();
    await page.keyboard.press("Escape");
    await expect(page.getByRole("dialog")).toBeVisible();
    await expect.poll(() => page.evaluate(() => window.indirectosMutation?.args.indirectos_porcentaje)).toBe(20);
    assert.equal(await page.evaluate(() => typeof window.indirectosMutation?.args.expected_impact), "string");
    assert.equal(await page.evaluate(() => "nombre" in window.indirectosMutation.args), false);
    assert.equal(await page.evaluate(() => "descripcion" in window.indirectosMutation.args), false);
    assert.equal(await page.evaluate(() => "honorarios_porcentaje" in window.indirectosMutation.args), false);
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    await page.screenshot({ path: `${root}/output/indirectos-ui/budget-${width}.png`, fullPage: true });
    await page.evaluate(() => { delete window.indirectosMutation; });
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    await field.fill("0");
    await expect(review).toBeVisible();
    await page.getByRole("button", { name: "Cancelar", exact: true }).click();
    assert.equal(await page.evaluate(() => window.indirectosMutation), undefined);
    // First activation at zero keeps its distinct copy and does not mutate on close.
    await page.evaluate(() => window.feeFixtureChange({ project: { indirectos_porcentaje: undefined, indirectos_fecha_inicio: undefined } }));
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    await expect(field).toHaveValue("");
    await field.fill("0");
    await expect(review).toContainText("La activación sustituye componentes manuales desde la fecha de inicio, incluso al 0%.");
    await page.keyboard.press("Escape");
    assert.equal(await page.evaluate(() => window.indirectosMutation), undefined);
    // Exclusions reduce the approved denominator per concept. Paid charges
    // are distributed through a family and five leaves using the real engine.
    await page.goto("http://127.0.0.1:4197/e2e/indirectos/preview.html?view=budget");
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    await page.getByRole("checkbox", { name: "Calcular Honorarios desde presupuesto", exact: true }).check();
    await page.getByRole("checkbox", { name: "Calcular General Conditions desde presupuesto", exact: true }).check();
    await page.getByRole("checkbox", { name: "Calcular Viáticos desde presupuesto", exact: true }).check();
    await expect(page.locator('[id^="exclude-honorarios-"]')).toHaveCount(5);
    await expect(page.getByTestId("rate-honorarios")).toHaveText("11.74%");
    await expect(page.getByTestId("rate-viaticos")).toHaveText("1.41%");
    await page.getByText("Partidas excluidas de la base de Honorarios (0)", { exact: true }).click();
    await page.getByLabel("Buscar partidas para excluir en Honorarios", { exact: true }).fill("viaticos");
    await expect(page.locator('[id^="exclude-honorarios-"]')).toHaveCount(1);
    await page.getByLabel("Buscar partidas para excluir en Honorarios", { exact: true }).fill("");
    for (const id of ["fee", "gc", "travel", "misc"]) await page.locator(`#exclude-honorarios-${id}`).check();
    await expect(page.getByTestId("rate-honorarios")).toHaveText("15.00%");
    await expect(page.getByTestId("rate-viaticos")).toHaveText("1.41%");
    await page.getByText("Partidas excluidas de la base de Honorarios (4)", { exact: true }).click();
    await page.getByText("Partidas excluidas de la base de Viáticos (0)", { exact: true }).click();
    for (const id of ["fee", "gc", "travel", "misc"]) await page.locator(`#exclude-viaticos-${id}`).check();
    await expect(page.getByTestId("rate-viaticos")).toHaveText("1.80%");
    await page.getByText("Partidas excluidas de la base de Viáticos (4)", { exact: true }).click();
    await expect(page.getByTestId("concept-review-honorarios")).toContainText("$255,600.00");
    await expect(page.getByTestId("concept-review-honorarios")).toContainText("Aprobado excluido: $55,600.00");
    await expect(page.getByTestId("concept-review-honorarios")).toContainText("Base aprobada después de exclusiones: $200,000.00");
    await expect(page.getByTestId("concept-review-viaticos")).toContainText("acumulado completo del proyecto");
    await expect(save).toBeEnabled();
    await scrollSection(page.getByRole("checkbox", { name: "Calcular Honorarios desde presupuesto", exact: true }));
    await page.screenshot({ path: `${root}/output/indirectos-ui/concept-exclusions-${width}.png` });
    await scrollSection(page.getByTestId("concept-review-honorarios"));
    await page.screenshot({ path: `${root}/output/indirectos-ui/concepts-review-${width}.png` });
    await save.click();
    await expect.poll(() => page.evaluate(() => window.indirectosMutation?.args.fee_concepts?.length)).toBe(3);
    const savedConcepts = await page.evaluate(() => window.indirectosMutation.args.fee_concepts);
    assert.deepEqual([...savedConcepts.find(c => c.concepto === "honorarios").excluded_partidas].sort(), ["fee", "gc", "misc", "travel"]);
    assert.deepEqual([...savedConcepts.find(c => c.concepto === "viaticos").excluded_partidas].sort(), ["fee", "gc", "misc", "travel"]);
    assert.equal(savedConcepts.find(c => c.concepto === "general_conditions").excluded_partidas.length, 0);
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    await page.getByRole("button", { name: "Expandir VIÁTICOS", exact: true }).click();
    await page.getByRole("button", { name: "Expandir Gastos de viaje", exact: true }).click();
    const travelRow = page.getByRole("row").filter({ has: page.getByRole("button", { name: "Contraer VIÁTICOS", exact: true }) });
    await expect(travelRow).toContainText("1,800");
    await expect(travelRow.getByRole("cell").nth(4)).toContainText("50.00%");
    await expect(page.getByRole("row").filter({ hasText: "HONORARIOS" }).first().getByRole("cell").nth(4)).toContainText("50.00%");
    for (let index = 1; index <= 5; index++) {
      const leaf = page.getByRole("row").filter({ hasText: `Viático ${index}` });
      await expect(leaf).toBeVisible();
      await expect(leaf).toContainText(index === 1 ? "180" : index === 3 ? "540" : "360");
      await expect(leaf.getByRole("cell").nth(4)).toContainText("50.00%");
    }
    await page.getByText('El proyecto "Obra de prueba" ha sido actualizado correctamente.').waitFor({ state: "hidden" });
    await page.screenshot({ path: `${root}/output/indirectos-ui/concepts-breakdown-${width}.png`, fullPage: true });
    await page.evaluate(() => window.feeFixtureChange({ approvedWork: 400000 }));
    await expect(travelRow).toContainText("900");
    await expect(travelRow.getByRole("cell").nth(4)).toContainText("25.00%");
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    await expect(page.getByTestId("rate-honorarios")).toHaveText("7.50%");
    await expect(page.getByTestId("rate-viaticos")).toHaveText("0.90%");
    await expect(page.getByRole("button", { name: "Guardar Cambios", exact: true })).toBeDisabled();
    // Only changing exclusions must generate a new review and payload.
    await page.getByText("Partidas excluidas de la base de Honorarios (4)", { exact: true }).click();
    await page.locator("#exclude-honorarios-work").check();
    await expect(page.getByRole("alert").filter({ hasText: "presupuesto aprobado menos exclusiones" }).first()).toBeVisible();
    await expect(save).toBeDisabled();
    await page.locator("#exclude-honorarios-work").uncheck();
    await page.locator("#exclude-honorarios-misc").uncheck();
    await expect(page.getByTestId("rate-honorarios")).toHaveText("7.43%");
    await expect(save).toBeEnabled();
    await save.click();
    await expect.poll(() => page.evaluate(() => window.indirectosMutation?.args.fee_concepts?.find(c => c.concepto === "honorarios").excluded_partidas.includes("misc"))).toBe(false);
    await page.getByRole("dialog").waitFor({ state: "hidden" });
    await page.getByRole("button", { name: "Editar proyecto de prueba" }).click();
    await expect(page.getByTestId("rate-honorarios")).toHaveText("7.43%");
    await expect(save).toBeDisabled();
    await page.getByRole("button", { name: "Cancelar", exact: true }).click();
    await page.goto("http://127.0.0.1:4197/e2e/indirectos/preview.html");
    await expect(page.getByText("INDIRECTOS COBRADOS", { exact: true }).filter({ visible: true }).first()).toBeVisible();
    await expect(page.getByText("SALDO DE INDIRECTOS", { exact: true }).filter({ visible: true }).first()).toBeVisible();
    const balanceRows = page.getByRole("row").filter({ hasText: "SALDO DE INDIRECTOS" });
    await expect(balanceRows.last()).toContainText(width === 1440 ? "3.0k" : "3,000");
    await page.screenshot({ path: `${root}/output/indirectos-ui/pnl-${width}.png`, fullPage: true });
    assert.deepEqual(errors, []);
    await page.close();
  }
  console.log("Indirectos UI passed: approved budget minus exclusions, exclusion-only saves, invalid net bases, leaf distribution, preview, monthly scope, concurrency, field conflicts, failures, cancellation, desktop and mobile. Synthetic fixtures only.");
} finally {
  await browser?.close(); await server.httpServer.close();
}
